// Get translation by key (flat key, no dot traversal)
function t(key, lang) {
  if (!key) return '';
  const targetLang = lang || currentLang || 'en';
  const dict = I18N[targetLang] || I18N.en || {};
  return dict[key] ?? key;
}

// Replace placeholders like {var} in translation string
function tReplace(str, vars) {
  return str.replace(/\{(\w+)\}/g, (match, key) => {
    return vars[key] !== undefined ? vars[key] : match;
  });
}

// Apply language to all elements with data-i18n
function applyLang(lang) {
  currentLang = lang;
  window.currentLang = currentLang;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;

    const translated = t(key, lang);

    // If translation missing, keep existing fallback text (do NOT leak the key)
    if (!translated || translated === key) return;

    el.textContent = translated;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (!key) return;

    const ph = t(key, lang);

    // Only set placeholder if translation exists
    if (!ph || ph === key) return;

    el.placeholder = ph;
  });

  // Use new key with fallback to legacy
  document.title = t('g.site.suschurch.title', lang) || t('title', lang);

  try {
    localStorage.setItem('sus_lang', lang);
  } catch (e) {
    // ignore
  }

  window.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));
}

// Get saved language or default
let currentLang = 'en';
try {
  const saved = localStorage.getItem('sus_lang');
  if (saved && I18N[saved]) {
    currentLang = saved;
  }
} catch (e) {
  // ignore
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('sus_lang');
  const lang = (saved && I18N[saved]) ? saved : 'en';
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
  applyLang(lang);
});

// Fallback translation helper: try multiple keys, return first match
function t2(keys, lang) {
  if (!Array.isArray(keys) || keys.length === 0) return '';
  const targetLang = lang || currentLang || 'en';
  const dict = I18N[targetLang] || I18N.en || {};
  for (const k of keys) {
    if (dict[k] !== undefined) return dict[k];
  }
  // Fallback: return first key (so you can see missing)
  return keys[0] || '';
}

// Minimal: apply i18n only inside a subtree root (instead of whole document)
function applyLangTo(root, lang) {
  if (!root) return;

  const L = lang || currentLang || 'en';

  // text nodes
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;

    const translated = t(key, L);

    // If translation missing, keep existing fallback text
    if (!translated || translated === key) return;

    el.textContent = translated;
  });

  // placeholders (inputs/textarea)
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (!key) return;

    const ph = t(key, L);

    // Only set placeholder if translation exists
    if (!ph || ph === key) return;

    el.setAttribute('placeholder', ph);
  });
}

